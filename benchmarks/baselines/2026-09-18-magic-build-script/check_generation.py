"""Check deterministic output and Cargo rebuild inputs in an isolated snapshot."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--label", default="rebuild-check", help="Unique output/target prefix")
args = parser.parse_args()
label = args.label
if not label or any(c not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-_" for c in label):
    parser.error("--label must use only ASCII letters, digits, hyphens, and underscores")

output = Path(__file__).resolve().parent
root = output.parents[2]
review = root / "target/reviews/magic-build-script"
workspace = review / label
target = root / "target/build-benchmarks/magic-build-script" / label
report = output / f"{label}.json"
if workspace.exists() or target.exists() or report.exists():
    parser.error("check already exists; use a new --label")

measured_files = sorted((root / "target/build-benchmarks/magic-build-script").glob("after-*/**/out/magic_attacks.rs"))
assert len(measured_files) == 6, "expected the six independently generated benchmark outputs"
digests = {hashlib.sha256(path.read_bytes()).hexdigest() for path in measured_files}
assert len(digests) == 1, "generated output differs between clean builds or profiles"
expected_digest = digests.pop()

shutil.copytree(review / "after", workspace)
command = ["cargo", "build", "--manifest-path", str(workspace / "Cargo.toml"),
           "-p", "penteconter", "--lib", "--locked", "--offline", "--target-dir", str(target)]

def build(name):
    with (output / f"{label}-{name}.log").open("x") as stream:
        subprocess.run(command, cwd=root, stdout=stream, stderr=subprocess.STDOUT, check=True)
    files = list(target.glob("debug/build/penteconter-*/out/magic_attacks.rs"))
    assert len(files) == 1
    generated = files[0]
    assert hashlib.sha256(generated.read_bytes()).hexdigest() == expected_digest
    return generated.stat().st_mtime_ns

previous = build("initial")
assert build("unchanged") == previous, "unchanged build unnecessarily regenerated the table"
build_script = workspace / "crates/penteconter/build.rs"
inputs = re.findall(r'^        "([^"]+)",$', build_script.read_text(), re.MULTILINE)
assert len(inputs) == 8, "unexpected rebuild dependency list"
checks = []
for index, source in enumerate(inputs):
    path = workspace / "crates/penteconter" / source
    # Mutate only the isolated copy; this leaves behavior and generated bytes intact.
    with path.open("a") as stream:
        stream.write("\n// Cargo regeneration check.\n")
    current = build(f"input-{index + 1}")
    assert current > previous, f"changing {source} did not regenerate the table"
    checks.append(source)
    print(f"Regenerated after changing {source}; output unchanged", flush=True)
    previous = current

result = {"working_directory": str(root), "command": command,
          "generated_files_compared": [str(path) for path in measured_files],
          "sha256": expected_digest, "unchanged_build_skips_generation": True,
          "inputs_verified": checks}
report.write_text(json.dumps(result, indent=2) + "\n")
print(f"Verified {len(measured_files)} identical clean-build outputs and {len(checks)} rebuild inputs.")
